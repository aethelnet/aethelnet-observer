    def __init__(self, db_path: str = "market_data.db"):
        self.db_path = db_path
        # Ensure directory exists if a nested path is provided
        db_dir = os.path.dirname(os.path.abspath(db_path))
        if db_dir and not os.path.exists(db_dir):
            try:
                os.makedirs(db_dir, exist_ok=True)
            except Exception:
                # In case of permission issues, continue and let sqlite raise later
                pass

        self._init_db()

        # in-memory caches to avoid recomputing heavy analyses (bounded to prevent memory bloat)
        self._analysis_cache = OrderedDict()  # key: (symbol, analysis_type) -> (cached_at, ts, payload)
        self._analysis_cache_max = 1000
        self._signals_cache = {}   # key: symbol -> {'ts': float, 'data': list}
        self._cache_ttl = 30.0     # seconds
        self._cache_lock = threading.Lock()

        # Run migrations if DB schema is behind.
        try:
            self._migrate()
        except Exception:
            logger.exception("Migration step failed during initialization")

    def _connect(self) -> sqlite3.Connection:
        """Create a connection with sensible defaults for concurrent reads/writes."""
        conn = sqlite3.connect(self.db_path, timeout=30.0, detect_types=sqlite3.PARSE_DECLTYPES)
        conn.row_factory = sqlite3.Row
        try:
            # Improve concurrency & durability for multi-threaded producers/consumers
            conn.execute("PRAGMA journal_mode=WAL;")
            conn.execute("PRAGMA synchronous=NORMAL;")
            conn.execute("PRAGMA foreign_keys=ON;")
        except Exception:
            # Some SQLite builds may not support WAL or PRAGMAs; ignore failures but log.
            logger.debug("Could not set PRAGMAs on connection.")
        return conn

