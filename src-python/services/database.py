    def _get_schema_version(self) -> int:
        """Return current schema version stored in DB (0 if missing)."""
        try:
            with self._connect() as conn:
                cur = conn.execute("SELECT version FROM schema_version ORDER BY version DESC LIMIT 1")
                r = cur.fetchone()
                if not r:
                    return 0
                # sqlite3.Row supports dict-style access; fallback to index
                return int(r["version"]) if "version" in r.keys() else int(r[0])
        except sqlite3.OperationalError as e:
            # If table doesn't exist, we are at version 0
            if "no such table" in str(e).lower():
                return 0
            logger.exception("Operational error reading schema version")
            return 0
        except Exception:
            logger.exception("Error reading schema version")
            return 0

