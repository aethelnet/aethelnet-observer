    # ---------- Wallets ----------
    def upsert_wallet(self, user_id: int, balances: dict, vault: dict):
        """Persist wallet state to DB."""
        try:
            now_ts = time.time()
            balances_json = json.dumps(balances)
            vault_json = json.dumps(vault)
            with self._connect() as conn:
                conn.execute(
                    """
                    INSERT INTO wallets (user_id, balances, vault, updated_ts)
                    VALUES (?, ?, ?, ?)
                    ON CONFLICT(user_id) DO UPDATE SET
                        balances=excluded.balances,
                        vault=excluded.vault,
                        updated_ts=excluded.updated_ts
                    """,
                    (user_id, balances_json, vault_json, now_ts)
                )
                conn.commit()
        except Exception:
            logger.exception("Error upserting wallet")

    def get_wallet_state(self, user_id: int):
        """Retrieve wallet state from DB."""
        try:
            with self._connect() as conn:
                cur = conn.execute("SELECT balances, vault FROM wallets WHERE user_id = ?", (user_id,))
                row = cur.fetchone()
                if row:
                    return {
                        "balances": json.loads(row["balances"]),
                        "vault": json.loads(row["vault"])
                    }
                return None
        except Exception:
            logger.exception("Error getting wallet state")
            return None

