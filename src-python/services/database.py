    def get_latest_analysis(self, symbol: Optional[str], analysis_type: str):
        """
        Get the most recent analysis for (symbol, analysis_type).
        Uses in-memory cache when fresh; falls back to DB and repopulates cache.

        Note: cache entries are stored as (cached_at, ts, payload). We check cached_at
        against _cache_ttl to determine freshness. When returning, we present the DB ts
        and payload to callers.
        """
        try:
            now = time.time()
            key = (symbol, analysis_type)
            with self._cache_lock:
                entry = self._analysis_cache.get(key)
                # entry -> (cached_at, ts, payload)
                if entry and (now - entry[0]) < self._cache_ttl:
                    return {"ts": entry[1], "payload": entry[2]}

            # Query DB for latest row. Handle NULL symbol specially.
            with self._connect() as conn:
                if symbol is None:
                    cur = conn.execute(
                        "SELECT ts, payload FROM analyses WHERE symbol IS NULL AND analysis_type = ? ORDER BY ts DESC LIMIT 1",
                        (analysis_type,),
                    )
                else:
                    cur = conn.execute(
                        "SELECT ts, payload FROM analyses WHERE symbol = ? AND analysis_type = ? ORDER BY ts DESC LIMIT 1",
                        (symbol, analysis_type),
                    )
                r = cur.fetchone()
                if not r:
                    return None
                payload = json.loads(r["payload"]) if r["payload"] else None
                ts = r["ts"]
                with self._cache_lock:
                    # store (cached_at, ts, payload)
                    self._analysis_cache[key] = (time.time(), ts, payload)
                    # Evict oldest if cache grows beyond limit
                    try:
                        if len(self._analysis_cache) > self._analysis_cache_max:
                            self._analysis_cache.popitem(last=False)
                    except Exception:
                        pass
                return {"ts": ts, "payload": payload}
        except Exception:
            logger.exception("Error getting latest analysis")
            return None

    def get_or_compute_analysis(self, symbol: Optional[str], ts: float, analysis_type: str, compute_fn, force: bool = False):
        """
        Helper to return existing latest analysis if recent enough, otherwise compute using
        the provided compute_fn (callable returning payload), store it, and return it.
        This centralizes the 'check DB/cache then compute then persist' pattern to cut down
        on repeated expensive recalculations across strategies/ML pipelines.
        """
        try:
            if not force:
                existing = self.get_latest_analysis(symbol, analysis_type)
                if existing and existing["ts"] >= ts:
                    return existing

            # compute, store, and return
            payload = compute_fn()
            self.insert_analysis(symbol, ts, analysis_type, payload)
            return {"ts": ts, "payload": payload}
        except Exception:
            logger.exception("Error in get_or_compute_analysis")
            return None

    # ---------- Signals ----------
    def insert_signal(self, symbol: Optional[str], ts: float, signal: str, params: Any = None):
        """
        Insert a signal and update the in-memory recent-signals cache.
        The cache is best-effort: failures to update are non-fatal.

        Returns:
            The inserted signal row id on success, or None on failure.
        """
        try:
            params_json = json.dumps(params, default=str) if params is not None else None
            with self._connect() as conn:
                cur = conn.execute(
                    "INSERT INTO signals (symbol, ts, signal, params) VALUES (?, ?, ?, ?)",
                    (symbol, ts, signal, params_json),
                )
                conn.commit()
                sid = cur.lastrowid
            # update cache (best-effort)
            try:
                with self._cache_lock:
                    if symbol not in self._signals_cache:
                        self._signals_cache[symbol] = {"ts": time.time(), "data": []}
                    entry = self._signals_cache[symbol]
                    # prepend for newest-first ordering and keep up to a reasonable cap
                    entry["data"].insert(0, {"symbol": symbol, "ts": ts, "signal": signal, "params": params, "id": sid})
                    entry["data"] = entry["data"][:1000]
                    entry["ts"] = time.time()
            except Exception:
                logger.debug("Failed to update signals cache", exc_info=True)
            return sid
        except Exception:
            logger.exception("Error inserting signal")
            return None

    def get_signals(self, symbol: Optional[str] = None, limit: int = 1000):
        """
        Fetch signals. If a recent cached value exists for the symbol, return that (best-effort).
        Otherwise query the DB and refresh the cache.
        """
        try:
            now = time.time()
            if symbol is not None:
                with self._cache_lock:
                    cached = self._signals_cache.get(symbol)
                    if cached and (now - cached["ts"]) < self._cache_ttl:
                        return cached["data"][:limit]

            with self._connect() as conn:
                params = []
                clauses = []
                if symbol is not None:
                    clauses.append("symbol = ?")
                    params.append(symbol)
                where = ("WHERE " + " AND ".join(clauses)) if clauses else ""
                limit = int(limit)
                cur = conn.execute(
                    f"SELECT id, symbol, ts, signal, params, created_ts FROM signals {where} ORDER BY ts DESC LIMIT ?",
                    (*params, limit),
                )
                rows = cur.fetchall()
                results = [
                    {
                        "id": r["id"],
                        "symbol": r["symbol"],
                        "ts": r["ts"],
                        "signal": r["signal"],
                        "params": json.loads(r["params"]) if r["params"] else None,
                        "created_ts": r["created_ts"],
                    }
                    for r in rows
                ]
                # refresh cache for this symbol (if specified)
                try:
                    if symbol is not None:
                        with self._cache_lock:
                            self._signals_cache[symbol] = {"ts": time.time(), "data": results}
                except Exception:
                    logger.debug("Failed to refresh signals cache")
                return results
        except Exception:
            logger.exception("Error getting signals")
            return []

