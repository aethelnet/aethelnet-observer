    # ---------- Market ticks (unchanged functionality, safer connections) ----------
    def insert_tick(self, symbol: str, timestamp: float, price: float, volume: float, is_buyer_maker: bool):
        """Insert a single tick. Uses INSERT OR REPLACE to handle overlaps."""
        try:
            with self._connect() as conn:
                conn.execute(
                    "INSERT OR REPLACE INTO market_ticks (symbol, timestamp, price, volume, is_buyer_maker) VALUES (?, ?, ?, ?, ?)",
                    (symbol, timestamp, price, volume, 1 if is_buyer_maker else 0),
                )
                conn.commit()
        except Exception:
            logger.exception("Error inserting tick")

    def insert_batch(self, ticks: List[Tuple]):
        """
        Insert a batch of ticks.
        ticks format: [(symbol, timestamp, price, volume, is_buyer_maker), ...]
        This method includes a short retry loop to handle transient SQLITE_LOCKED errors.
        """
        if not ticks:
            return

        attempts = 3
        delay = 0.05
        formatted_ticks = [(t[0], t[1], t[2], t[3], 1 if t[4] else 0) for t in ticks]
        for attempt in range(attempts):
            try:
                with self._connect() as conn:
                    conn.executemany(
                        "INSERT OR REPLACE INTO market_ticks (symbol, timestamp, price, volume, is_buyer_maker) VALUES (?, ?, ?, ?, ?)",
                        formatted_ticks,
                    )
                    conn.commit()
                return
            except sqlite3.OperationalError as e:
                # Retry on database locked
                if "locked" in str(e).lower() and attempt + 1 < attempts:
                    time.sleep(delay * (2 ** attempt))
                    continue
                logger.exception("SQLite operational error inserting batch")
                return
            except Exception:
                logger.exception("Error inserting batch")
                return

    def get_latest_timestamp(self, symbol: str) -> float:
        """Get the timestamp of the most recent tick for a symbol."""
        try:
            with self._connect() as conn:
                cur = conn.execute("SELECT MAX(timestamp) as mx FROM market_ticks WHERE symbol = ?", (symbol,))
                row = cur.fetchone()
                return float(row["mx"]) if row and row["mx"] is not None else 0.0
        except Exception:
            logger.exception("Error getting latest timestamp")
            return 0.0

    def get_history(self, symbol: str, limit: int = 20000) -> List[Tuple]:
        """Get the most recent N ticks for a symbol, ordered by timestamp ASC."""
        try:
            with self._connect() as conn:
                # Use parametrized query for limit by casting to int here (safe)
                limit = int(limit)
                cur = conn.execute(
                    "SELECT timestamp, price, volume, is_buyer_maker FROM market_ticks WHERE symbol = ? ORDER BY timestamp DESC LIMIT ?",
                    (symbol, limit),
                )
                rows = cur.fetchall()
                # Convert sqlite3.Row to tuples and reverse for chronological order
                return [ (r["timestamp"], r["price"], r["volume"], r["is_buyer_maker"]) for r in rows ][::-1]
        except Exception:
            logger.exception("Error fetching history")
            return []

    # ---------- Analyses ----------
    def insert_analysis(self, symbol: Optional[str], ts: float, analysis_type: str, payload: Any):
        """Store an analysis result. Payload will be JSON-serialized.
        Also update an in-memory cache so expensive recalculation can be avoided.

        Notes:
        - Uses a short retry loop on sqlite 'database is locked' OperationalError.
        - Cache update remains best-effort and non-blocking to callers.
        """
        payload_json = json.dumps(payload, default=str)
        attempts = 3
        delay = 0.05
        for attempt in range(attempts):
            try:
                with self._connect() as conn:
                    conn.execute(
                        "INSERT INTO analyses (symbol, ts, analysis_type, payload) VALUES (?, ?, ?, ?)",
                        (symbol, ts, analysis_type, payload_json),
                    )
                    conn.commit()
                # update in-memory cache (best-effort, non-critical)
                try:
                    key = (symbol, analysis_type)
                    now = time.time()
                    with self._cache_lock:
                        existing = self._analysis_cache.get(key)
                        # existing format: (cached_at, ts, payload)
                        if not existing or ts >= existing[1]:
                            # store cached insertion time, the DB ts, and the payload
                            self._analysis_cache[key] = (now, ts, payload)
                            # Evict oldest if cache grows beyond limit
                            try:
                                if len(self._analysis_cache) > self._analysis_cache_max:
                                    self._analysis_cache.popitem(last=False)
                            except Exception:
                                pass
                except Exception:
                    logger.debug("Failed to update analysis cache", exc_info=True)
                return
            except sqlite3.OperationalError as e:
                if "locked" in str(e).lower() and attempt + 1 < attempts:
                    time.sleep(delay * (2 ** attempt))
                    continue
                logger.exception("SQLite operational error inserting analysis")
                return
            except Exception:
                logger.exception("Error inserting analysis")
                return

